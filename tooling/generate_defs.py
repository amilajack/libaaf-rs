#!/usr/bin/env python3
"""Generate checked-in Rust definitions from the pinned reference (development only)."""
from pathlib import Path
import re, struct
root = Path(__file__).resolve().parents[1]
ref = root / 'tooling/reference'
constants = {}
for path in sorted((ref / 'include/libaaf/AAFDefs').glob('*.h')):
    text = re.sub(r'/\*.*?\*/', '', path.read_text(), flags=re.S)
    for name, body in re.findall(r'static const aafUID_t\s+(\w+)\s*=\s*\{(.*?)\};', text, re.S):
        nums = [int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]+)', body)]
        if len(nums) == 11:
            constants[name] = struct.pack('<IHH8B', *nums)
    for name, val in re.findall(r'#define\s+(PID_\w+)\s+(0x[0-9a-fA-F]+)', text):
        constants[name] = int(val, 16)
for path in sorted((ref / 'include/libaaf/AAFDefs').glob('*.h')):
    for name, target in re.findall(r'#define\s+(AAF\w+)\s+(AAF\w+)', path.read_text()):
        if target in constants: constants[name] = constants[target]
out = ['// Derived from LibAAF; copyright (C) 2017-2024 Adrien Gesta-Fline.',
       '// SPDX-License-Identifier: GPL-2.0-or-later', '// Generated by tooling/generate_defs.py. Do not edit.',
       '#![allow(non_upper_case_globals)]', 'use crate::Uid;']
for name, value in constants.items():
    out.append(f'pub const {name}: ' + (f'u16 = 0x{value:04x};' if isinstance(value, int) else f'Uid = Uid({list(value)!r});'))
for table, prefix in [('UID_NAMES', 'AAF'), ('PROPERTY_NAMES', 'PID_')]:
    typ = 'Uid' if table == 'UID_NAMES' else 'u16'
    out.append(f'pub static {table}: &[({typ}, &str)] = &[')
    for name, val in constants.items():
        if (isinstance(val, int)) == (typ == 'u16'):
            out.append(f'({name}, "{name}"),')
    out.append('];')
classes = re.sub(r'/\*.*?\*/', '', (ref / 'src/AAFCore/AAFClass.c').read_text(), flags=re.S)
out.append('pub static STANDARD_CLASSES: &[(Uid, Option<Uid>, bool)] = &[')
variables = {}
for var, uid, concrete, parent in re.findall(r'aafClass\s*\*\s*(\w+)\s*=\s*aafclass_defineNewClass\(\s*aafd,\s*&(\w+),\s*(\w+),\s*(\w+)\s*\)', classes):
    variables[var] = uid
    out.append(f'({uid}, ' + ('None' if parent == 'NULL' else f'Some({variables[parent]})') + f', {str(concrete == "CONCRETE").lower()}),')
out.append('];')
out.append('pub static STANDARD_PROPERTIES: &[(Uid, u16, bool)] = &[')
for var, pid, required in re.findall(r'attachNewProperty\(\s*aafd,\s*(\w+),\s*prop,\s*(\w+),\s*(\w+)\s*\)', classes):
    if var in variables:
        out.append(f'({variables[var]}, {pid}, {str(required == "PROP_REQ").lower()}),')
out.append('];')
(root / 'crates/libaaf/src/defs.rs').write_text('\n'.join(out) + '\n')
print(f'Generated {len(constants)} constants, {len(variables)} classes')
